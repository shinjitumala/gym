use std::{env, fs, path::PathBuf};

/// Embed the hydrated bundle so installing stays one file.
///
/// `cargo leptos build` writes the script, the WASM module and the stylesheet
/// into `target/site/pkg`; this copies whatever is there into `OUT_DIR` and
/// writes an `assets.rs` that includes it. A plain `cargo build` — what the
/// tests and a CLI-only install use — finds no site, embeds nothing, and the
/// binary still builds; `gym web` then says what is missing instead of serving
/// an empty page.
fn main() {
    built::write_built_file().expect("Failed to acquire build-time information");
    println!("cargo:rerun-if-changed=style/main.css");
    println!("cargo:rerun-if-changed=migrations");
    println!("cargo:rerun-if-changed=target/site/pkg");
    let site = PathBuf::from("target/site/pkg");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let files = out_dir.join("files");
    fs::create_dir_all(&files).expect("create the asset directory");

    let mut code = String::from("// generated by build.rs\n");
    for (name, ident) in [
        ("gym.js", "JS"),
        ("gym.wasm", "MODULE"),
        ("gym_bg.wasm", "BINDGEN"),
        ("gym.css", "CSS"),
    ] {
        let src = site.join(name);
        println!("cargo:rerun-if-changed={}", src.display());
        if src.exists() {
            let dst = files.join(name);
            fs::copy(&src, &dst).expect("copy an asset");
            code.push_str(&format!(
                "pub const {ident}: Option<&'static [u8]> = Some(include_bytes!(r\"{}\"));\n",
                dst.display()
            ));
        } else {
            code.push_str(&format!(
                "pub const {ident}: Option<&'static [u8]> = None;\n"
            ));
        }
    }
    code.push_str(
        "pub fn wasm() -> Option<&'static [u8]> { MODULE.or(BINDGEN) }\n\
         pub fn embedded() -> bool { JS.is_some() && wasm().is_some() }\n",
    );
    fs::write(out_dir.join("assets.rs"), code).expect("write assets.rs");
}
